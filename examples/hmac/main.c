/* RFC 2104 section 2 from the streaming hash:
 * H((K0 ^ opad) || H((K0 ^ ipad) || text)) */
static int ref256(const uint8_t *k, uint32_t kl, const uint8_t *m, uint32_t ml, uint8_t *out)
{
    uint8_t k0[64], pad[64], inner[32];
    sha256_ctx_t c;
    uint32_t i;
    int rc = 0;

    for (i = 0; i < 64; i++)
        k0[i] = 0;
    if (kl > 64) {
        rc |= sha256_stream_init(&c);
        rc |= sha256_stream_update(&c, k, kl);
        rc |= sha256_stream_final(&c, k0);
    } else {
        for (i = 0; i < kl; i++)
            k0[i] = k[i];
    }
    for (i = 0; i < 64; i++)
        pad[i] = k0[i] ^ 0x36;
    rc |= sha256_stream_init(&c);
    rc |= sha256_stream_update(&c, pad, 64);
    rc |= sha256_stream_update(&c, m, ml);
    rc |= sha256_stream_final(&c, inner);
    for (i = 0; i < 64; i++)
        pad[i] = k0[i] ^ 0x5C;
    rc |= sha256_stream_init(&c);
    rc |= sha256_stream_update(&c, pad, 64);
    rc |= sha256_stream_update(&c, inner, 32);
    rc |= sha256_stream_final(&c, out);
    return rc;
}

static int ref512(const uint8_t *k, uint32_t kl, const uint8_t *m, uint32_t ml, uint8_t *out)
{
    uint8_t k0[128], pad[128], inner[64];
    sha512_ctx_t c;
    uint32_t i;
    int rc = 0;

    for (i = 0; i < 128; i++)
        k0[i] = 0;
    if (kl > 128) {
        rc |= sha512_hash(k, kl, k0);
    } else {
        for (i = 0; i < kl; i++)
            k0[i] = k[i];
    }
    for (i = 0; i < 128; i++)
        pad[i] = k0[i] ^ 0x36;
    rc |= sha512_stream_init(&c);
    rc |= sha512_stream_update(&c, pad, 128);
    rc |= sha512_stream_update(&c, m, ml);
    rc |= sha512_stream_final(&c, inner);
    for (i = 0; i < 128; i++)
        pad[i] = k0[i] ^ 0x5C;
    rc |= sha512_stream_init(&c);
    rc |= sha512_stream_update(&c, pad, 128);
    rc |= sha512_stream_update(&c, inner, 64);
    rc |= sha512_stream_final(&c, out);
    return rc;
}

int main(void)
{
    uint8_t d[64], e[64];
    uint32_t i, j, n, bad;
    int rc;

    bao_init();
    mini_printf("\r\nhmac start\r\n");

    for (i = 0; i < 7; i++) {
        const tc_t *t = &cases[i];
        n = t->trunc ? t->trunc : 32;
        rc = hmac_sha256(t->key, t->key_len, t->msg, t->msg_len, d);
        mini_printf("HMAC-SHA256 case %u: ", (unsigned)(i + 1));
        hex(d, n);
        result(rc == SHA_OK && same(d, t->t256, n));
        n = t->trunc ? t->trunc : 64;
        rc = hmac_sha512(t->key, t->key_len, t->msg, t->msg_len, d);
        mini_printf("HMAC-SHA512 case %u: ", (unsigned)(i + 1));
        hex(d, n);
        result(rc == SHA_OK && same(d, t->t512, n));
    }

    for (i = 0; i < 7; i++) {
        const tc_t *t = &cases[i];
        hmac_sha256_ctx_t a;
        hmac_sha512_ctx_t b;
        rc = hmac_sha256_init(&a, t->key, t->key_len);
        rc |= hmac_sha512_init(&b, t->key, t->key_len);
        for (j = 0; j < t->msg_len; j++) {
            rc |= hmac_sha256_update(&a, t->msg + j, 1);
            rc |= hmac_sha512_update(&b, t->msg + j, 1);
        }
        rc |= hmac_sha256_final(&a, d);
        rc |= hmac_sha512_final(&b, e);
        mini_printf("case %u a byte at a time, SHA-256 and SHA-512 in turn:", (unsigned)(i + 1));
        result(rc == SHA_OK && same(d, t->t256, t->trunc ? t->trunc : 32) &&
               same(e, t->t512, t->trunc ? t->trunc : 64));
    }

    for (bad = 0, j = 0; j <= cases[6].msg_len; j++) {
        hmac_sha256_ctx_t a;
        hmac_sha512_ctx_t b;
        rc = hmac_sha256_init(&a, cases[6].key, cases[6].key_len);
        rc |= hmac_sha256_update(&a, cases[6].msg, j);
        rc |= hmac_sha256_update(&a, cases[6].msg + j, cases[6].msg_len - j);
        rc |= hmac_sha256_final(&a, d);
        bad += rc != SHA_OK || !same(d, cases[6].t256, 32);
        rc = hmac_sha512_init(&b, cases[6].key, cases[6].key_len);
        rc |= hmac_sha512_update(&b, cases[6].msg, j);
        rc |= hmac_sha512_update(&b, cases[6].msg + j, cases[6].msg_len - j);
        rc |= hmac_sha512_final(&b, e);
        bad += rc != SHA_OK || !same(e, cases[6].t512, 64);
    }
    mini_printf("case 7 at all %u split points, wrong: %u", (unsigned)(cases[6].msg_len + 1), (unsigned)bad);
    result(bad == 0);

    {
        /* case 6 on SHA-256, case 7 on SHA-512 and SHA-256 of "abc", in turn */
        hmac_sha256_ctx_t a;
        hmac_sha512_ctx_t b;
        sha256_ctx_t c;
        uint8_t f[32];
        static const uint8_t abc256[32] = {
            0xba, 0x78, 0x16, 0xbf, 0x8f, 0x01, 0xcf, 0xea, 0x41, 0x41, 0x40, 0xde, 0x5d, 0xae, 0x22, 0x23,
            0xb0, 0x03, 0x61, 0xa3, 0x96, 0x17, 0x7a, 0x9c, 0xb4, 0x10, 0xff, 0x61, 0xf2, 0x00, 0x15, 0xad,
        };  /* FIPS 180-2 appendix B.1 */
        rc = hmac_sha256_init(&a, cases[5].key, cases[5].key_len);
        rc |= sha256_stream_init(&c);
        rc |= hmac_sha512_init(&b, cases[6].key, cases[6].key_len);
        for (j = 0; j < cases[6].msg_len; j += 10) {
            uint32_t k = cases[6].msg_len - j < 10 ? cases[6].msg_len - j : 10;
            if (j < cases[5].msg_len)
                rc |= hmac_sha256_update(&a, cases[5].msg + j,
                                         cases[5].msg_len - j < 10 ? cases[5].msg_len - j : 10);
            if (j < 3)
                rc |= sha256_stream_update(&c, (const uint8_t *)"abc" + j, 1);
            rc |= hmac_sha512_update(&b, cases[6].msg + j, k);
        }
        rc |= sha256_stream_update(&c, (const uint8_t *)"bc", 2);
        rc |= hmac_sha512_final(&b, e);
        rc |= sha256_stream_final(&c, f);
        rc |= hmac_sha256_final(&a, d);
        mini_printf("two HMAC contexts and a SHA-256 context in turn:");
        result(rc == SHA_OK && same(d, cases[5].t256, 32) && same(e, cases[6].t512, 64) &&
               same(f, abc256, 32));
    }

    for (i = 0; i < sizeof(key); i++)
        key[i] = (uint8_t)(i * 29 + 7);
    for (i = 0; i < sizeof(msg); i++)
        msg[i] = (uint8_t)(i * 11 + 1);
    {
        static const uint16_t kl[] = {0, 1, 63, 64, 65, 127, 128, 129, 300, 600};
        static const uint16_t ml[] = {0, 55, 56, 64, 111, 112, 200, 2000};
        uint32_t wrong256 = 0, wrong512 = 0;
        for (i = 0; i < sizeof(kl) / sizeof(kl[0]); i++) {
            for (j = 0; j < sizeof(ml) / sizeof(ml[0]); j++) {
                rc = hmac_sha256(key, kl[i], msg, ml[j], d);
                rc |= ref256(key, kl[i], msg, ml[j], e);
                wrong256 += rc != SHA_OK || !same(d, e, 32);
                rc = hmac_sha512(key, kl[i], msg, ml[j], d);
                rc |= ref512(key, kl[i], msg, ml[j], e);
                wrong512 += rc != SHA_OK || !same(d, e, 64);
            }
        }
        mini_printf("HMAC-SHA256 against RFC 2104 for 10 key and 8 message lengths, wrong: %u",
                    (unsigned)wrong256);
        result(wrong256 == 0);
        mini_printf("HMAC-SHA512 against RFC 2104 for 10 key and 8 message lengths, wrong: %u",
                    (unsigned)wrong512);
        result(wrong512 == 0);
        rc = hmac_sha256(key, 600, msg, 2000, d);
        mini_printf("HMAC-SHA256 600 byte key, 2000 bytes: ");
        hex(d, 32);
        mini_printf("\r\n");
        rc = hmac_sha512(key, 600, msg, 2000, d);
        mini_printf("HMAC-SHA512 600 byte key, 2000 bytes: ");
        hex(d, 64);
        mini_printf("\r\n");
    }

    {
        hmac_sha256_ctx_t a;
        int r1, r2, r3;
        r1 = hmac_sha256_init(&a, NULL, 5);
        hmac_sha256_init(&a, cases[1].key, cases[1].key_len);
        hmac_sha256_final(&a, d);
        r2 = hmac_sha256_update(&a, msg, 3);
        r3 = hmac_sha256_final(&a, d);
        mini_printf("return codes: NULL key %d, after final %d %d", r1, r2, r3);
        result(r1 == SHA_ERR_ARG && r2 == SHA_ERR_STATE && r3 == SHA_ERR_STATE);
    }

    mini_printf("[Done] hmac %d of %d passed\r\n", passed, total);
    while (1)
        __asm__ volatile ("wfi");
}
